"""
Bug Test Generator
==================

Generates bug-specific tests that:
1. Reproduce the exact bug condition
2. FAIL before the fix (confirming bug exists)
3. PASS after the fix (confirming bug is fixed)

This is the key to autonomous debugging - if we can't reproduce it, we can't fix it.

Language-agnostic: Uses LanguageDetector to generate tests in the project's language.
"""

import asyncio
import logging
import subprocess
import tempfile
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Dict, Any

from ..services.language_detector import LanguageDetector, LanguageInfo

logger = logging.getLogger(__name__)


@dataclass
class TestResult:
    """Result of running a test."""
    passed: bool
    output: str
    error: Optional[str] = None
    duration_seconds: float = 0.0


class BugTestGenerator:
    """
    Generate tests that reproduce specific bugs.

    The generated test should:
    1. Set up the conditions that trigger the bug
    2. Execute the code path that fails
    3. Assert what SHOULD happen (will fail when bug exists)
    """

    # Template for generated bug tests
    TEST_TEMPLATE = '''"""
Bug-specific test generated by RAICA.

Bug Description: {bug_description}
Generated: {timestamp}
"""

import pytest
import sys
from pathlib import Path

# Add project to path
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

{imports}


class TestBug_{test_id}:
    """Test case for: {bug_description_short}"""

    def test_bug_reproduction(self):
        """
        This test reproduces the bug.
        - Should FAIL before fix (bug exists)
        - Should PASS after fix (bug resolved)
        """
        {test_body}
'''

    def __init__(self, llm_client: Any, project_dir: Path, language_detector: Optional[LanguageDetector] = None):
        self.llm_client = llm_client
        self.project_dir = project_dir
        self.language_detector = language_detector or LanguageDetector(project_dir)
        self._ui_framework_cache = None

    def _check_dependency(self, python_path: str, import_name: str) -> bool:
        """Check if a dependency can be imported in the given Python environment."""
        try:
            cmd = [python_path, "-c", f"import {import_name}"]
            subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            return True
        except (subprocess.CalledProcessError, FileNotFoundError):
            return False

    def _install_dependency(self, python_path: str, package_name: str) -> bool:
        """Install a dependency into the project venv."""
        try:
            logger.info(f"[Install] Installing {package_name} into project venv...")
            cmd = [python_path, "-m", "pip", "install", package_name, "-q"]
            result = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
            if result.returncode == 0:
                logger.info(f"[Install] ✓ Successfully installed {package_name}")
                return True
            else:
                logger.warning(f"[Install] ✗ Failed to install {package_name}: {result.stderr}")
                return False
        except subprocess.TimeoutExpired:
            logger.warning(f"[Install] ✗ Timeout installing {package_name}")
            return False
        except Exception as e:
            logger.warning(f"[Install] ✗ Error installing {package_name}: {e}")
            return False

    def _ensure_test_dependencies(self, python_path: str) -> bool:
        """
        Ensure the project venv has all required test dependencies.
        Installs missing dependencies automatically.

        Returns:
            True if all dependencies are available (installed or already present)
        """
        # Required: pytest
        if not self._check_dependency(python_path, "pytest"):
            logger.info(f"[Dependencies] pytest not found, installing...")
            if not self._install_dependency(python_path, "pytest"):
                return False

        # Framework-specific dependencies
        framework = self._detect_ui_framework()
        logger.info(f"[Dependencies] Detected UI framework: {framework}")

        if framework in ('pyqt5', 'pyqt6', 'pyside2', 'pyside6'):
            if not self._check_dependency(python_path, "pytestqt"):
                logger.info(f"[Dependencies] pytest-qt not found for {framework} project, installing...")
                if not self._install_dependency(python_path, "pytest-qt"):
                    return False
            if not self._check_dependency(python_path, "pytest_mock"):
                logger.info(f"[Dependencies] pytest-mock not found, installing...")
                self._install_dependency(python_path, "pytest-mock")  # Optional, don't fail if missing

        logger.info(f"[Dependencies] ✓ All test dependencies satisfied")
        return True

    def _create_venv(self) -> Optional[Path]:
        """Create a new virtual environment for the project."""
        try:
            logger.info(f"[PythonPath] Creating new venv at {self.project_dir / '.venv'}...")
            subprocess.run([sys.executable, "-m", "venv", str(self.project_dir / ".venv")], check=True)
            
            venv_path = self.project_dir / ".venv"
            python_bin = venv_path / "bin" / "python"
            if not python_bin.exists():
                python_bin = venv_path / "Scripts" / "python.exe"
            
            if python_bin.exists():
                logger.info(f"[PythonPath] ✓ Created venv: {python_bin}")
                # Upgrade pip
                subprocess.run([str(python_bin), "-m", "pip", "install", "--upgrade", "pip"], 
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                return python_bin
            return None
        except Exception as e:
            logger.error(f"[PythonPath] Failed to create venv: {e}")
            return None

    def _get_project_python_path(self) -> str:
        """
        Get the path to the python executable for this project.
        Finds project venv and ensures test dependencies are installed.

        IMPORTANT: This method ONLY uses the project's venv. It will NOT
        fall back to RAICA's venv or system Python for running project tests.
        """
        venv_names = [".venv", "venv", "env"]

        logger.info(f"[PythonPath] Searching for venv in project_dir: {self.project_dir}")

        for name in venv_names:
            venv_path = self.project_dir / name
            if venv_path.exists() and venv_path.is_dir():
                # Check for bin/python (Linux/Mac) or Scripts/python.exe (Windows)
                python_bin = venv_path / "bin" / "python"
                if not python_bin.exists():
                    python_bin = venv_path / "Scripts" / "python.exe"  # Windows

                if python_bin.exists() and python_bin.is_file():
                    logger.info(f"[PythonPath] Found project venv: {python_bin}")
                    # Ensure test dependencies are installed (installs if missing)
                    if self._ensure_test_dependencies(str(python_bin)):
                        logger.info(f"[PythonPath] ✓ Using project venv with all dependencies: {python_bin}")
                        return str(python_bin)
                    else:
                        logger.error(f"[PythonPath] ✗ Failed to ensure dependencies in {venv_path}")
                        # Still use project venv - better to fail clearly than use wrong env
                        return str(python_bin)

        # No project venv found - attempt to create one
        logger.warning(f"[PythonPath] ✗ No project venv found in {self.project_dir}")
        logger.info(f"[PythonPath] Attempting to auto-create virtual environment...")
        
        created_python = self._create_venv()
        if created_python:
            # Install dependencies if requirements.txt exists
            req_file = self.project_dir / "requirements.txt"
            if req_file.exists():
                logger.info(f"[PythonPath] Installing requirements from {req_file}...")
                subprocess.run([str(created_python), "-m", "pip", "install", "-r", str(req_file)],
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            
            # Ensure test dependencies
            if self._ensure_test_dependencies(str(created_python)):
                 return str(created_python)
        
        # Return system python as last resort, but log a clear warning
        system_python = Path("/usr/bin/python3")
        if system_python.exists():
            logger.warning(f"[PythonPath] ⚠ Using system python (may fail for project imports): {system_python}")
            return str(system_python)

        raise RuntimeError(f"No Python environment found and failed to create one at {self.project_dir}.")

    def _detect_ui_framework(self) -> Optional[str]:
        """
        Detect the UI framework used in the project.

        Returns:
            Framework name: 'pyqt5', 'pyqt6', 'pyside2', 'pyside6', 'tkinter',
                           'wxpython', 'kivy', 'react', 'vue', 'angular', 'electron', None
        """
        if self._ui_framework_cache is not None:
            logger.debug(f"[Framework] Using cached: {self._ui_framework_cache}")
            return self._ui_framework_cache

        logger.info(f"[Framework] Detecting UI framework in: {self.project_dir}")
        # Check requirements.txt for Python UI frameworks
        req_file = self.project_dir / "requirements.txt"
        logger.info(f"[Framework] Checking {req_file}, exists={req_file.exists()}")
        if req_file.exists():
            try:
                content = req_file.read_text().lower()
                if 'pyqt5' in content:
                    logger.info(f"[Framework] ✓ Found PyQt5 in requirements.txt")
                    self._ui_framework_cache = 'pyqt5'
                    return 'pyqt5'
                elif 'pyqt6' in content:
                    self._ui_framework_cache = 'pyqt6'
                    return 'pyqt6'
                elif 'pyside2' in content:
                    self._ui_framework_cache = 'pyside2'
                    return 'pyside2'
                elif 'pyside6' in content:
                    self._ui_framework_cache = 'pyside6'
                    return 'pyside6'
                elif 'wxpython' in content or 'wx' in content:
                    self._ui_framework_cache = 'wxpython'
                    return 'wxpython'
                elif 'kivy' in content:
                    self._ui_framework_cache = 'kivy'
                    return 'kivy'
            except Exception:
                pass

        # Check for tkinter usage in Python files
        try:
            for py_file in self.project_dir.rglob("*.py"):
                if py_file.is_file():
                    content = py_file.read_text()
                    if 'import tkinter' in content or 'from tkinter' in content:
                        self._ui_framework_cache = 'tkinter'
                        return 'tkinter'
                    if 'from PyQt5' in content or 'import PyQt5' in content:
                        self._ui_framework_cache = 'pyqt5'
                        return 'pyqt5'
                    if 'from PyQt6' in content or 'import PyQt6' in content:
                        self._ui_framework_cache = 'pyqt6'
                        return 'pyqt6'
                    if 'from PySide2' in content or 'import PySide2' in content:
                        self._ui_framework_cache = 'pyside2'
                        return 'pyside2'
                    if 'from PySide6' in content or 'import PySide6' in content:
                        self._ui_framework_cache = 'pyside6'
                        return 'pyside6'
        except Exception:
            pass

        # Check package.json for JS frameworks
        pkg_json = self.project_dir / "package.json"
        if pkg_json.exists():
            try:
                import json
                content = json.loads(pkg_json.read_text())
                deps = {**content.get('dependencies', {}), **content.get('devDependencies', {})}
                if 'react' in deps:
                    self._ui_framework_cache = 'react'
                    return 'react'
                elif 'vue' in deps:
                    self._ui_framework_cache = 'vue'
                    return 'vue'
                elif '@angular/core' in deps:
                    self._ui_framework_cache = 'angular'
                    return 'angular'
                elif 'electron' in deps:
                    self._ui_framework_cache = 'electron'
                    return 'electron'
            except Exception:
                pass

        self._ui_framework_cache = None
        return None

    async def _get_llm_framework_guidance(self, bug_description: str, file_contents: Dict[str, str]) -> str:
        """
        Ask the LLM to identify framework-specific constraints for testing.

        This is the intelligent approach - the LLM analyzes the actual code
        and bug context to provide relevant framework constraints, rather
        than relying on hardcoded heuristics.

        Returns framework-specific guidance string for the test generation prompt.
        """
        # Build a sample of the code for context
        code_sample = ""
        for path, content in list(file_contents.items())[:3]:
            truncated = content[:2000] if len(content) > 2000 else content
            code_sample += f"\n--- {path} ---\n{truncated}\n"

        prompt = f"""Analyze this code and identify any UI/framework-specific constraints that affect testing.

BUG/FEATURE: {bug_description}

CODE SAMPLE:
{code_sample}

TASK: Identify the UI framework (if any) and provide CRITICAL testing constraints.

Think about:
1. What UI framework is this? (Qt/PyQt, Tkinter, React, Vue, Angular, Electron, Flutter, SwiftUI, etc.)
2. What are the LIMITATIONS of this framework that could cause incorrect tests?
3. What assertions would be WRONG vs RIGHT for this framework?

OUTPUT FORMAT (plain text, will be inserted into test generation prompt):
If a UI framework is detected, provide constraints like:

FRAMEWORK CONSTRAINTS for [FrameworkName]:
==========================================
1. [Limitation 1 - what the framework does NOT support]
2. [Limitation 2]
...

CORRECT TESTING APPROACH:
- [How to properly test visual/UI elements in this framework]
- [What assertions to use vs avoid]

EXAMPLE:
- WRONG: [incorrect assertion approach]
- RIGHT: [correct assertion approach]

If no special framework constraints apply, respond with: NO_FRAMEWORK_CONSTRAINTS
"""

        try:
            response = await asyncio.to_thread(
                self.llm_client.generate,
                prompt=prompt,
                temperature=0.2,
                max_tokens=1500
            )

            if not response.success:
                logger.warning(f"LLM framework guidance failed: {response.error}")
                return self._get_framework_specific_guidance()  # Fall back to static

            content = response.content.strip()

            if "NO_FRAMEWORK_CONSTRAINTS" in content:
                return ""

            logger.info(f"LLM framework guidance received ({len(content)} chars)")
            return f"\n{content}\n"

        except Exception as e:
            logger.warning(f"LLM framework guidance error: {e}")
            return self._get_framework_specific_guidance()  # Fall back to static

