    def _get_test_command(self, test_file: Path) -> List[str]:
        """Get the language-appropriate test command for a file."""
        lang = self.language_detector.detect()

        # Use language-specific test command, but replace generic args with specific file
        base_cmd = lang.test_command.copy()

        # Most test frameworks accept the file path as an argument
        if lang.short_name == "python":
            python_path = self._get_project_python_path()
            return [python_path, "-m", "pytest", str(test_file), "-v", "--tb=short", "-x"]
        elif lang.short_name in ["javascript", "typescript"]:
            return ["npx", "jest", str(test_file), "--verbose"]
        elif lang.short_name == "go":
            return ["go", "test", "-v", "-run", test_file.stem, "./..."]
        elif lang.short_name == "rust":
            return ["cargo", "test", test_file.stem, "--", "--nocapture"]
        elif lang.short_name == "java":
            # Maven/Gradle - test specific class
            return ["mvn", "test", f"-Dtest={test_file.stem}"]
        else:
            # Fall back to base command with file appended
            return base_cmd + [str(test_file)]

    async def run_test(self, test_file: Path, timeout: int = 60) -> TestResult:
        """
        Run a test file and return the result (language-aware).

        Args:
            test_file: Path to the test file
            timeout: Maximum seconds to wait

        Returns:
            TestResult with pass/fail status and output
        """
        # Check if language requires manual testing
        lang = self.language_detector.detect()
        if lang.test_framework == "manual":
            logger.info(f"[TestRun] {lang.name} requires manual testing - cannot run automated tests")
            return TestResult(
                passed=True,  # Assume pass - user must verify manually
                output=f"MANUAL TESTING REQUIRED: {lang.name} projects must be tested by running the application.\n"
                       f"Please run: {' '.join(lang.test_command)}",
                error=None,
                duration_seconds=0.0
            )

        import time
        start_time = time.time()

        try:
            # Get language-appropriate test command
            cmd = self._get_test_command(test_file)
            logger.info(f"Running test with command: {' '.join(cmd)}")

            result = await asyncio.to_thread(
                subprocess.run,
                cmd,
                cwd=str(self.project_dir),
                capture_output=True,
                text=True,
                timeout=timeout
            )

            duration = time.time() - start_time
            passed = result.returncode == 0

            return TestResult(
                passed=passed,
                output=result.stdout,
                error=(result.stdout + "\n" + result.stderr) if not passed else None,
                duration_seconds=duration
            )

        except subprocess.TimeoutExpired:
            return TestResult(
                passed=False,
                output="",
                error=f"Test timed out after {timeout} seconds",
                duration_seconds=timeout
            )
        except Exception as e:
            return TestResult(
                passed=False,
                output="",
                error=str(e),
                duration_seconds=time.time() - start_time
            )

    async def verify_test_fails(self, test_file: Path) -> bool:
        """
        Verify the bug test FAILS (confirming bug exists).

        Returns True if test fails (expected before fix).
        """
        result = await self.run_test(test_file)
        if not result.passed:
            logger.info("Bug test FAILS as expected (bug confirmed)")
            return True
        else:
            logger.warning("Bug test PASSES - hypothesis may be wrong")
            return False

    async def verify_test_passes(self, test_file: Path, timeout: int = 60) -> bool:
        """
        Verify the bug test PASSES (confirming bug is fixed).

        Args:
            test_file: Path to test file
            timeout: Maximum seconds to wait (default 60)

        Returns True if test passes (expected after fix).
        """
        result = await self.run_test(test_file, timeout=timeout)
        if result.passed:
            logger.info("Bug test PASSES - fix verified!")
            return True
        else:
            logger.warning(f"Bug test still FAILS - fix incomplete: {result.error}")
            return False

    async def get_test_error(self, test_file: Path) -> Optional[str]:
        """
        Get the error message from running a test.

        Returns the error message if test fails, None if passes.
        """
        result = await self.run_test(test_file)
        return result.error

    def identify_relevant_tests(self, modified_files: List[str]) -> List[Path]:
        """
        Identify existing tests that verify the modified files.
        Uses naming conventions and import scanning.
        """
        relevant_tests = set()
        
        # Gather all test files
        all_tests = []
        test_roots = [
            self.project_dir / "tests",
            self.project_dir / "test",
            self.project_dir
        ]
        
        for root in test_roots:
            if root.exists():
                if root.is_dir():
                    all_tests.extend(list(root.rglob("test_*.py")))
                    all_tests.extend(list(root.rglob("*_test.py")))
                else:
                    # project dir itself
                    all_tests.extend(list(root.glob("test_*.py")))

        all_tests = list(set(all_tests)) # unique
        
        # Use Dependency Graph for robust detection
        from ..services.dependency_graph import DependencyGraphService
        graph = DependencyGraphService(self.project_dir)
        graph.build_graph()
        
        for mod_file in modified_files:
            # Get all files that depend on this modified file
            dependents = graph.get_dependents(mod_file, recursive=True)
            
            # Also check the file itself if it's a test
            if "test" in mod_file or "tests" in mod_file:
                 dependents.add(mod_file)

            # Filter for test files
            for dep in dependents:
                if "test" in dep or "tests" in dep: # Simple heuristics for test files
                     # Confirm it's a python file and exists
                     p = self.project_dir / dep
                     if p.exists() and p.name.endswith('.py') and (p.name.startswith("test_") or p.name.endswith("_test.py")):
                         # EXCLUDE historical bug reproduction tests
                         if not p.name.startswith("test_bug_"):
                             relevant_tests.add(p)
            
            # Fallback: maintain direct name matching for safety
            mod_path = Path(mod_file)
            mod_stem = mod_path.stem
            for test in all_tests:
                if test.name.startswith("test_bug_"):
                    continue # Skip bug tests
                
                if f"test_{mod_stem}" in test.name or f"{mod_stem}_test" in test.name:
                    relevant_tests.add(test)
        
        # Filter out test files with broken imports
        # This prevents false positive regressions from test pollution
        validated_tests = []
        for test_path in relevant_tests:
            if self._test_file_is_valid(test_path):
                validated_tests.append(test_path)
            else:
                logger.warning(f"Skipping test with broken imports: {test_path}")
        
        return validated_tests
    
    def _test_file_is_valid(self, test_path: Path) -> bool:
        """
        Quick check if a test file can be collected without import errors.
        Returns False if the file has broken imports.
        """
        try:
            result = subprocess.run(
                [self._get_project_python_path(), "-c", f"import ast; ast.parse(open('{test_path}').read())"],
                capture_output=True,
                text=True,
                timeout=5,
                cwd=str(self.project_dir)
            )
            if result.returncode != 0:
                return False
            
            # Check for obvious import issues by reading the file
            content = test_path.read_text(encoding='utf-8', errors='replace')
            
            # Look for imports that are known to be problematic
            problematic_imports = ['astroid', 'pylint']  # These are dev tools, not runtime deps
            for line in content.split('\n'):
                line = line.strip()
                if line.startswith('import ') or line.startswith('from '):
                    for prob_import in problematic_imports:
                        if prob_import in line:
                            return False
            
            return True
        except Exception:
            return False

    async def run_targeted_tests(self, test_paths: List[Path], timeout: int = 60) -> TestResult:
        """
        Run a specific list of test files.
        
        Args:
            test_paths: List of test files to run
            timeout: Timeout in seconds
            
        Returns:
            TestResult
        """
        if not test_paths:
            return TestResult(True, "No relevant tests identified to run.", duration_seconds=0.0)
            
        import time
        start_time = time.time()
        
        try:
            python_path = self._get_project_python_path()
            cmd = [python_path, "-m", "pytest", "-v", "--tb=short"]
            cmd.extend([str(p) for p in test_paths])
            
            result = await asyncio.to_thread(
                subprocess.run,
                cmd,
                cwd=str(self.project_dir),
                capture_output=True,
                text=True,
                timeout=timeout
            )

            duration = time.time() - start_time
            passed = result.returncode == 0

            return TestResult(
                passed=passed,
                output=result.stdout,
                error=(result.stdout + "\n" + result.stderr) if not passed else None,
                duration_seconds=duration
            )
            
        except subprocess.TimeoutExpired:
             return TestResult(False, "", f"Targeted tests timed out after {timeout}s", timeout)
        except Exception as e:
             return TestResult(False, "", str(e), time.time() - start_time)

    async def run_all_project_tests(self, timeout: int = 120) -> TestResult:
        """
        Run all tests in the project to check for regressions.

        Returns:
            TestResult for the entire test suite
        """
        import time
        start_time = time.time()

        # Check for test directory or test files
        test_locations = [
            self.project_dir / "tests",
            self.project_dir / "test",
        ]

        test_dir = None
        for loc in test_locations:
            if loc.exists():
                test_dir = loc
                break

        # Also look for test_*.py files in project root
        test_files = list(self.project_dir.glob("test_*.py"))

        if not test_dir and not test_files:
            logger.info("No existing tests found in project")
            return TestResult(
                passed=True,
                output="No existing tests found",
                duration_seconds=0.0
            )

        try:
            # Run pytest on the whole project
            python_path = self._get_project_python_path()
            cmd = [python_path, "-m", "pytest", "-v", "--tb=short"]
            if test_dir:
                cmd.append(str(test_dir))
            else:
                cmd.extend([str(f) for f in test_files])

            result = await asyncio.to_thread(
                subprocess.run,
                cmd,
                cwd=str(self.project_dir),
                capture_output=True,
                text=True,
                timeout=timeout
            )

            duration = time.time() - start_time
            passed = result.returncode == 0

            return TestResult(
                passed=passed,
                output=result.stdout,
                error=(result.stdout + "\n" + result.stderr) if not passed else None,
                duration_seconds=duration
            )

        except subprocess.TimeoutExpired:
            return TestResult(
                passed=False,
                output="",
                error=f"Tests timed out after {timeout} seconds",
                duration_seconds=timeout
            )
        except Exception as e:
            return TestResult(
                passed=False,
                output="",
                error=str(e),
                duration_seconds=time.time() - start_time
            )
