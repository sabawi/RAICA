    async def _handle_system_task(
        self,
        request: str,
        classification: ClassificationResult
    ) -> OrchestratorResult:
        """
        Handle system modification tasks using TWO-PHASE plan generation.

        This ensures we INVESTIGATE first, then decide whether to EXECUTE existing
        scripts or CODE_GENERATE new ones based on what investigation found.

        Phase 1: Generate and execute INVESTIGATE steps only
        Phase 2: Generate action steps based on investigation results
        """
        await self._output("Planning system task (2-phase approach)...", "info")

        # ═══════════════════════════════════════════════════════════════════════
        # PHASE 1: INVESTIGATION - Find what already exists
        # ═══════════════════════════════════════════════════════════════════════
        await self._output("Phase 1: Investigating project state...", "info")

        # Generate investigation-only plan
        investigate_plan = await self._generate_investigation_plan(request, classification)

        if investigate_plan.steps:
            # Execute investigation steps
            for step in investigate_plan.steps:
                if step.step_type == StepType.INVESTIGATE:
                    step.status = StepStatus.IN_PROGRESS
                    await self._output(f"  🔍 {step.title}", "info")
                    success = await self._execute_query_step(step, [])
                    step.status = StepStatus.COMPLETED if success else StepStatus.FAILED

        # Collect investigation results
        investigation_output = self._collect_investigation_results(investigate_plan)
        await self._output(f"Investigation found:\n{investigation_output[:500]}...", "info")

        # ═══════════════════════════════════════════════════════════════════════
        # PHASE 2: ACTION PLANNING - Decide EXECUTE vs CODE_GENERATE
        # ═══════════════════════════════════════════════════════════════════════
        await self._output("\nPhase 2: Planning actions based on investigation...", "info")

        # Generate action plan informed by investigation results
        action_plan = await self._generate_action_plan(request, classification, investigation_output)
        self._current_plan = action_plan

        # Show plan summary
        summary = self.decomposer.get_plan_summary(action_plan)
        await self._output(f"\n{summary}", "info")

        # Get plan approval
        if self.callbacks.on_plan_ready:
            approved = await self.callbacks.on_plan_ready(action_plan)
            if not approved:
                await self._output("Plan not approved by user", "warning")
                return OrchestratorResult(
                    success=False,
                    request=request,
                    classification=classification,
                    plan=action_plan,
                    error="Plan not approved"
                )

        # Execute the action plan
        return await self._execute_plan(action_plan, request, classification)

